import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("legacy template nodes stay on their own page through edits, reload and export", async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem("talweg_lang", "en"));
  await page.goto("/");
  await page.getByRole("button", { name: /^Microservices Architecture/ }).click();
  const nodes = page.getByTestId("canvas-node");
  await expect(nodes).toHaveCount(6);
  const authId = await nodes.filter({ hasText: "Auth Service" }).getAttribute("data-node-id");
  const auth = page.locator(`[data-testid="canvas-node"][data-node-id="${String(authId)}"]`);
  await auth.dblclick({ position: { x: 60, y: 30 } });
  await auth.getByRole("textbox", { name: "Label", exact: true }).fill("First page private");
  await auth.getByRole("textbox", { name: "Label", exact: true }).press("Escape");
  await page.getByRole("button", { name: "Add page", exact: true }).click();
  await expect(nodes).toHaveCount(0);
  await expect(page.getByTestId("connector-label")).toHaveCount(0);
  await page.getByRole("button", { name: "Add to canvas", exact: true }).click();
  await page.getByRole("dialog", { name: "Add to canvas", exact: true }).getByRole("button", { name: "Rectangle", exact: true }).click();
  await nodes.dblclick({ position: { x: 60, y: 30 } });
  await nodes.getByRole("textbox", { name: "Label", exact: true }).fill("Second page only");
  await nodes.getByRole("textbox", { name: "Label", exact: true }).press("Escape");
  await page.reload();
  await expect(nodes).toHaveCount(1);
  await expect(nodes).toContainText("Second page only");
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download PNG", exact: true }).click();
  const path = await (await download).path();
  if (!path) throw new Error("Missing PNG");
  const png = await readFile(path);
  expect(png.readUInt32BE(16)).toBe(640);
  expect(png.readUInt32BE(20)).toBe(400);
  await page.getByTestId("page-tabs-bar").getByText("Page 1", { exact: true }).click();
  await expect(nodes).toHaveCount(6);
  await expect(page.getByText("First page private", { exact: true })).toBeVisible();
  await expect(page.getByText("Second page only", { exact: true })).toHaveCount(0);
  await page.reload();
  await expect(nodes).toHaveCount(6);
  await page.getByTestId("page-tabs-bar").getByText("Page 2", { exact: true }).click();
  await expect(nodes).toHaveCount(1);
  await expect(nodes).toContainText("Second page only");
  await nodes.click();
  await page.getByRole("button", { name: "Whiteboard", exact: true }).click();
  await page.getByRole("menuitemradio", { name: /^Mindmap/ }).click();
  await page.getByRole("button", { name: "Add Subtopic (Tab)", exact: true }).click();
  await expect(nodes).toHaveCount(2);
  await page.reload();
  await expect(nodes).toHaveCount(2);
  await page.getByTestId("page-tabs-bar").getByText("Page 1", { exact: true }).click();
  await expect(nodes).toHaveCount(6);

});
