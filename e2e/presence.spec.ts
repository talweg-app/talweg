import { test, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
import type { NodeId, ArrowNode } from '@talweg/core';
import { createBlankCanvas } from '../apps/web/src/utils/starterTemplates.js';
import { createCanvasNode } from '../apps/web/src/utils/createCanvasNode.js';
import { groupSelection } from '../apps/web/src/utils/organizeCanvas.js';
import { createSceneDoc, serializeTalwegFile } from '../packages/storage/src/index.js';

for (const theme of ['dark','light']) test(`participants see selections, live gestures and editing on their own page in ${theme}`, async ({page: host, browser}) => {
  test.setTimeout(90000);
  let doc = createBlankCanvas('doc-presence-audit');
  for (const [index, label] of ['Alpha','Beta','Grouped C','Grouped D'].entries()) {
    const node = createCanvasNode('rectangle', {x:0,y:0}, 'whiteboard');
    if (!node || node.type !== 'rectangle') throw new Error('Missing fixture');
    const box = {...node, id: `box-${index}` as NodeId, x: [120,580,120,420][index]!, y: index < 2 ? 100 : 400, pageId:'page-1', data:{label}};
    doc.nodes[box.id] = box; doc.rootNodeIds.push(box.id);
  }
  const a = doc.nodes['box-0' as NodeId]!;
  const arrow: ArrowNode = {...a, id:'arrow-audit' as NodeId, type:'arrow', width:0,height:0,x:0,y:0,data:{sourceId:a.id,targetId:'box-1' as NodeId,sourceAnchor:'e',targetAnchor:'w',curveStyle:'orthogonal',endArrow:'arrow'},style:{strokeColor:'#8caecc',strokeWidth:1.5}};
  doc.nodes[arrow.id]=arrow;
  doc = groupSelection(doc,new Set(['box-2','box-3'] as NodeId[]),'group-audit' as NodeId,'Audit group');
  const scene = createSceneDoc(doc); const content = serializeTalwegFile(doc,scene);scene.destroy();
  await host.addInitScript(() => { delete (window as Window & {showOpenFilePicker?:unknown}).showOpenFilePicker; });
  await host.goto('/');
  await host.getByRole('combobox',{name:'Appearance',exact:true}).selectOption(theme);
  const chooser = host.waitForEvent('filechooser');
  await host.getByRole('button',{name:'Open from Computer',exact:true}).click();
  await (await chooser).setFiles({name:'presence-audit.talweg',mimeType:'application/json',buffer:Buffer.from(content)});
  await expect(host.getByTestId('canvas-node')).toHaveCount(4);
  await host.getByRole('button',{name:'Collaborate',exact:true}).click();
  await host.getByRole('button',{name:'Start a session',exact:true}).click();
  await expect(host.getByRole('status').filter({hasText:'Waiting for a guest'})).toBeVisible();
  const invite=await host.getByRole('textbox',{name:'Invitation link',exact:true}).inputValue();
  const context=await browser.newContext();
  const report:Record<string,unknown>={};
  try {
    const guest=await context.newPage(); await guest.goto('/');
    await guest.getByRole('combobox',{name:'Appearance',exact:true}).selectOption(theme);
    await guest.getByRole('button',{name:'Join a session',exact:true}).click();
    await guest.getByRole('textbox',{name:'Invitation link',exact:true}).fill(invite);
    await guest.getByRole('button',{name:'Connect',exact:true}).click();
    await host.getByRole('button',{name:'Allow',exact:true}).click();
    await expect(guest.getByTestId('canvas-node')).toHaveCount(4);
    await host.getByRole('button',{name:'Collaborate',exact:true}).click();
    const node=(page:typeof host,id:string)=>page.getByTestId('canvas-node').and(page.locator(`[data-node-id="${id}"]`));
    const shape=node(guest,'box-0');
    await shape.click();
    await expect(host.locator('.remote-selection')).toHaveCount(1);
    report.shapeSelection=true;
    await expect(host.getByTestId('remote-cursor')).toHaveCount(1);
    report.cursorImmediatelyAfterSelection=1;
    report.selectionStyle=await host.locator('.remote-selection').evaluate(el=>({width:el.getBoundingClientRect().width,height:el.getBoundingClientRect().height,border:getComputedStyle(el).border,offsetLeft:el.getBoundingClientRect().left}));
    await guest.mouse.move(540,350);
    await expect(host.getByTestId('remote-cursor')).toHaveCount(1);
    await host.screenshot({path:test.info().outputPath('shape-selected.png')});
    await node(guest,'box-1').click({modifiers:['Shift']});
    await expect(host.locator('.remote-selection')).toHaveCount(2);report.multiSelection=true;
    await guest.getByTestId('canvas').click({position:{x:20,y:20}});
    await expect(host.locator('.remote-selection')).toHaveCount(0);report.clearSelection=true;
    await guest.getByRole('button',{name:'Move group',exact:true}).click();
    await expect(host.locator('.remote-selection')).toHaveCount(1);
    report.groupFrame=await host.getByTestId('canvas-group').boundingBox();
    report.groupSelection=await host.locator('.remote-selection').evaluate(el=>({width:el.getBoundingClientRect().width,height:el.getBoundingClientRect().height}));
    const groupFrame=await host.getByTestId('canvas-group').boundingBox();const groupOutline=await host.locator('.remote-selection').boundingBox();
    expect(groupOutline!.width).toBeCloseTo(groupFrame!.width+10,0);expect(groupOutline!.height).toBeCloseTo(groupFrame!.height+10,0);
    await host.screenshot({path:test.info().outputPath('group-selected.png')});
    const arrowPoint=await guest.getByTestId('connector-hit').evaluate(el=>{const path=el as SVGPathElement;const point=path.getPointAtLength(path.getTotalLength()/2).matrixTransform(path.getScreenCTM()!);return{x:point.x,y:point.y};});
    await guest.mouse.click(arrowPoint.x,arrowPoint.y);
    await expect(guest.locator('[data-arrow-endpoint]')).toHaveCount(2);
    report.arrowLocalSelectionHandleCount=2;
    await expect(host.getByTestId('remote-arrow-selection')).toHaveCount(1);
    report.arrowRemoteSelectionCount=await host.getByTestId('remote-arrow-selection').count();
    await shape.click();
    const before=await node(host,'box-0').getAttribute('style');
    const rect=await shape.boundingBox(); if(!rect)throw new Error('No box');
    await guest.mouse.move(rect.x+30,rect.y+30);await guest.mouse.down();await guest.mouse.move(rect.x+110,rect.y+75,{steps:6});
    await expect.poll(()=>node(host,'box-0').getAttribute('style')).not.toBe(before);
    report.liveDragVisible=true;
    await guest.mouse.up();
    await expect.poll(()=>node(host,'box-0').getAttribute('style')).not.toBe(before);report.dragAfterRelease=true;
    const committed=await node(host,'box-0').getAttribute('style');
    const handle=await guest.locator('[data-handle=se]').boundingBox();if(!handle)throw new Error('No resize handle');
    await guest.mouse.move(handle.x+handle.width/2,handle.y+handle.height/2);await guest.mouse.down();await guest.mouse.move(handle.x+45,handle.y+30,{steps:6});
    await expect.poll(()=>node(host,'box-0').getAttribute('style')).not.toBe(committed);report.liveResizeVisible=true;
    await guest.keyboard.press('Escape');await guest.mouse.up();
    await expect.poll(()=>node(host,'box-0').getAttribute('style')).toBe(committed);report.cancelledResizeRestoresGeometry=true;
    const canvas=await guest.getByTestId('canvas').boundingBox();const moved=await shape.boundingBox();if(!canvas||!moved)throw new Error('No selection geometry');
    await guest.mouse.move(canvas.x+10,canvas.y+10);await guest.mouse.down();await guest.mouse.move(moved.x+moved.width+15,moved.y+moved.height+15,{steps:8});
    await expect(host.getByTestId('remote-marquee')).toBeVisible();report.liveMarquee=true;
    await guest.mouse.up();await expect(host.getByTestId('remote-marquee')).toHaveCount(0);
    await shape.dblclick({position:{x:80,y:30}});
    await shape.getByRole('textbox').fill('Changed while typing');
    await expect(node(host,'box-0')).toContainText('Changed while typing');report.textUpdatesWhileFocused=true;
    await expect(host.getByTestId('remote-caret')).toHaveCount(1);
    await shape.getByRole('textbox').press('ControlOrMeta+a');
    await expect(host.getByTestId('remote-text-selection').first()).toBeVisible();
    report.sharedCaret=true;
    await shape.getByRole('textbox').press('Escape');
    await guest.keyboard.press('p');
    const inkBefore=await host.locator('[data-testid="canvas-node"][data-node-type="freehand"]').count();
    await guest.mouse.move(700,450);await guest.mouse.down();await guest.mouse.move(760,480,{steps:6});
    await expect(host.getByTestId('remote-ink')).toBeVisible();
    await guest.keyboard.press('Escape');await guest.mouse.up();await expect(host.getByTestId('remote-ink')).toHaveCount(0);
    await expect(host.locator('[data-testid="canvas-node"][data-node-type="freehand"]')).toHaveCount(inkBefore);report.cancelledInkDiscarded=true;
    await guest.keyboard.press('p');
    await guest.mouse.move(700,450);await guest.mouse.down();await guest.mouse.move(800,520,{steps:10});
    await expect(host.getByTestId('remote-ink')).toBeVisible();report.liveInkVisible=true;
    await guest.mouse.up();await expect(host.locator('[data-testid="canvas-node"][data-node-type="freehand"]')).toHaveCount(inkBefore+1);await expect(host.getByTestId('remote-ink')).toHaveCount(0);report.inkAfterRelease=true;
    await guest.keyboard.press('v');
    await guest.getByRole('button',{name:'Add to canvas',exact:true}).click();
    await guest.getByRole('dialog',{name:'Add to canvas',exact:true}).getByRole('button',{name:'Markdown note',exact:true}).click();
    const guestNote=guest.getByTestId('canvas-node').filter({has:guest.locator('.markdown-node')});
    const hostNote=host.getByTestId('canvas-node').filter({has:host.locator('.markdown-node')});
    await guestNote.getByRole('button',{name:'Open note',exact:true}).click();
    await guest.getByRole('textbox',{name:'Markdown text',exact:true}).fill('A shared note with a visible caret.');
    await expect(hostNote).toContainText('A shared note with a visible caret.');
    await hostNote.getByRole('button',{name:'Open note',exact:true}).click();
    await host.getByRole('tab',{name:'Edit description',exact:true}).click();
    await guest.getByRole('textbox',{name:'Markdown text',exact:true}).click();
    await guest.getByRole('textbox',{name:'Markdown text',exact:true}).press('ControlOrMeta+a');
    await expect(host.getByTestId('remote-text-selection').first()).toBeVisible();report.noteSelectionVisible=true;
    await host.getByRole('dialog',{name:'Node note',exact:true}).getByRole('button',{name:'Close',exact:true}).click();
    await guest.getByRole('dialog',{name:'Node note',exact:true}).getByRole('button',{name:'Close',exact:true}).click();
    await guest.keyboard.press('v');await shape.click();await expect(host.locator('.remote-selection')).toHaveCount(1);
    await guest.getByRole('button',{name:'Add page',exact:true}).click();
    await expect(guest.getByRole('tab',{name:'Page 2',exact:true})).toHaveAttribute('aria-selected','true');
    await expect(host.locator('.remote-selection')).toHaveCount(0);report.pageScope=true;
    await expect(host.getByRole('tab',{name:'Page 1',exact:true})).toHaveAttribute('aria-selected','true');report.independentPages=true;
    await host.getByRole('tab',{name:'Page 2',exact:true}).click();await guest.mouse.move(450,320);
    await expect(host.getByTestId('remote-cursor')).toHaveCount(1);report.cursorOnSecondPage=true;
  } finally { await writeFile(test.info().outputPath('observations.json'),JSON.stringify(report,null,2));await context.close(); }
});
