import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("settings apply to the canvas, persist, and remain available from its compact menu",async({page})=>{
  await page.goto("/");
  await page.getByRole("button",{name:"Settings",exact:true}).click();
  const dialog=page.getByRole("dialog",{name:"Settings",exact:true});
  await expect(dialog).toBeVisible();
  await dialog.getByRole("button",{name:"Canvas",exact:true}).click();
  await dialog.getByRole("checkbox",{name:"Show dot grid",exact:true}).uncheck();
  await dialog.getByRole("checkbox",{name:/Snap to grid/}).check();
  await dialog.getByRole("combobox",{name:"Mouse wheel",exact:true}).selectOption("pan");
  await dialog.getByRole("button",{name:"Done",exact:true}).click();
  await page.getByRole("button",{name:/^Blank Canvas/}).click();
  await expect(page.getByTestId("canvas")).toHaveCSS("background-image","none");
  await page.getByRole("button",{name:"Canvas settings",exact:true}).click();
  await expect(page.getByRole("menuitemcheckbox",{name:"Snap to grid",exact:true})).toHaveAttribute("aria-checked","true");
  await page.getByRole("menuitem",{name:/Settings/}).click();
  await dialog.getByRole("button",{name:"Hosting",exact:true}).click();
  await dialog.getByRole("textbox",{name:"Your name",exact:true}).fill("Ivan QA");
  await dialog.getByRole("combobox",{name:"Maximum guests",exact:true}).selectOption("1");
  await dialog.getByRole("button",{name:"Done",exact:true}).click();
  await page.reload();
  await page.keyboard.press("Control+Comma");
  await dialog.getByRole("button",{name:"Hosting",exact:true}).click();
  await expect(dialog.getByRole("textbox",{name:"Your name",exact:true})).toHaveValue("Ivan QA");
  await expect(dialog.getByRole("combobox",{name:"Maximum guests",exact:true})).toHaveValue("1");
});

test("welcome setup can be revisited and settings exports omit TURN credentials",async({page})=>{
  await page.goto("/");
  await page.getByRole("button",{name:"Settings",exact:true}).click();
  const dialog=page.getByRole("dialog",{name:"Settings",exact:true});
  await dialog.getByRole("button",{name:"Open welcome setup",exact:true}).click();
  const setup=page.getByRole("dialog",{name:"A space for your next idea.",exact:true});
  await expect(setup).toBeVisible();
  await setup.getByRole("textbox",{name:"Your name",exact:true}).fill("Desk User");
  await setup.getByRole("button",{name:"Start using Talweg",exact:true}).click();
  await page.getByRole("button",{name:"Settings",exact:true}).click();
  await dialog.getByRole("button",{name:"Hosting",exact:true}).click();
  await dialog.getByText("Advanced network settings",{exact:true}).click();
  await dialog.getByRole("textbox",{name:"Custom signaling relay",exact:true}).fill("https://invalid.example");
  await dialog.getByRole("button",{name:"Apply network settings",exact:true}).click();
  await expect(dialog.getByRole("status")).toContainText("Check the relay URL");
  await dialog.getByRole("textbox",{name:"Custom signaling relay",exact:true}).fill("");
  await dialog.getByRole("textbox",{name:"ICE / STUN / TURN",exact:true}).fill(JSON.stringify([{urls:"turns:turn.example.org",username:"private-user",credential:"private-secret"}]));
  await dialog.getByRole("button",{name:"Apply network settings",exact:true}).click();
  await dialog.getByRole("button",{name:"Files & application",exact:true}).click();
  const download=page.waitForEvent("download");
  await dialog.getByRole("button",{name:"Export settings",exact:true}).click();
  const path=await(await download).path();if(!path)throw new Error("No settings export");
  const content=await readFile(path,"utf8");
  expect(content).not.toContain("private-secret");expect(content).not.toContain("private-user");
  const exported=JSON.parse(content) as {version:number;preferences:{displayName:string}};
  expect(exported.version).toBe(1);expect(exported.preferences.displayName).toBe("Desk User");
});

test("settings reject malformed imports, restore preferences, and fit a short window",async({page})=>{
  await page.setViewportSize({width:800,height:600});
  await page.goto("/");
  await page.getByRole("button",{name:"Settings",exact:true}).click();
  const dialog=page.getByRole("dialog",{name:"Settings",exact:true});
  await dialog.getByRole("button",{name:"Files & application",exact:true}).click();
  const file=dialog.locator('input[type="file"]');
  await file.setInputFiles({name:"invalid.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify({version:1,preferences:[]}))});
  await expect(dialog.getByRole("status")).toContainText("not a supported Talweg settings file");
  await file.setInputFiles({name:"settings.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify({version:1,preferences:{displayName:"Imported User",grid:false,guestLimit:2},theme:"light",language:"en"}))});
  await expect(dialog.getByRole("status")).toHaveText("Settings saved.");
  const done=dialog.getByRole("button",{name:"Done",exact:true});
  const bounds=await done.boundingBox();
  expect(bounds).not.toBeNull();
  expect((bounds?.y??600)+(bounds?.height??1)).toBeLessThanOrEqual(600);
  await done.click();
  await page.getByRole("button",{name:/^Blank Canvas/}).click();
  await expect(page.getByTestId("canvas")).toHaveCSS("background-image","none");
  await page.keyboard.press("Control+Comma");
  await dialog.getByRole("button",{name:"Hosting",exact:true}).click();
  await expect(dialog.getByRole("textbox",{name:"Your name",exact:true})).toHaveValue("Imported User");
  await expect(dialog.getByRole("combobox",{name:"Maximum guests",exact:true})).toHaveValue("2");
  await page.keyboard.press("Escape");
  await expect(dialog).toBeHidden();
});
